"""Run the data-quality checks and write them as CSV and a readable Markdown report."""
from config import OUTPUT_DIR, RAW_FILES, SQL_DIR
from db import connect, run_sql_file

RAW_TABLES = {
    "olist_orders_dataset.csv": "raw_orders",
    "olist_order_items_dataset.csv": "raw_order_items",
    "olist_order_payments_dataset.csv": "raw_payments",
    "olist_order_reviews_dataset.csv": "raw_reviews",
    "olist_customers_dataset.csv": "raw_customers",
    "olist_sellers_dataset.csv": "raw_sellers",
    "olist_products_dataset.csv": "raw_products",
    "olist_geolocation_dataset.csv": "raw_geolocation",
    "product_category_name_translation.csv": "raw_category_translation",
}


def main() -> None:
    con = connect(read_only=True)
    checks = run_sql_file(con, SQL_DIR / "quality" / "data_quality_checks.sql")
    OUTPUT_DIR.mkdir(exist_ok=True)
    checks.to_csv(OUTPUT_DIR / "data_quality_report.csv", index=False)

    lines = [
        "# Data quality report",
        "",
        "Generated by `src/data_quality.py` from `sql/quality/data_quality_checks.sql`.",
        "Every count below is computed from the loaded data.",
        "",
        "## Source row counts",
        "",
        "| Source file | Rows loaded | Rows expected |",
        "|---|---:|---:|",
    ]
    for file_name, table in RAW_TABLES.items():
        loaded = con.execute(f"SELECT count(*) FROM {table}").fetchone()[0]
        lines.append(f"| {file_name} | {loaded:,} | {RAW_FILES[file_name]:,} |")

    for group, frame in checks.groupby("check_group", sort=False):
        lines += [
            "",
            f"## {group}",
            "",
            "| Check | Affected | Out of | % | How the model handles it |",
            "|---|---:|---:|---:|---|",
        ]
        for row in frame.itertuples():
            lines.append(
                f"| {row.check_name} | {int(row.affected_rows):,} | {int(row.total_rows):,} "
                f"| {row.pct_of_rows:.3f} | {row.handling} |"
            )

    (OUTPUT_DIR / "data_quality_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  {len(checks)} checks written to outputs/data_quality_report.(csv|md)")
    con.close()


if __name__ == "__main__":
    main()
