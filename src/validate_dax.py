"""Compute the expected value of every DAX measure in SQL and publish the checklist.

Writes powerbi/expected_values.csv and powerbi/EXPECTED_VALUES.md, and fails if a measure
defined in powerbi/measures.dax has no SQL-computed expected value (or vice versa).
"""
import re
import sys

from config import POWERBI_DIR, SQL_DIR
from db import connect, run_sql_file

MEASURE_PATTERN = re.compile(r"^\s*MEASURE\s+fact_orders\[(.+?)\]\s*=", re.MULTILINE)


def format_value(value: float, unit: str) -> str:
    if unit == "currency":
        return f"{value:,.2f}"
    if unit == "int":
        return f"{value:,.0f}"
    if unit == "pct":
        return f"{value:.2f}%"
    return f"{value:,.3f}".rstrip("0").rstrip(".")


def main() -> int:
    con = connect(read_only=True)
    expected = run_sql_file(con, SQL_DIR / "validation" / "dax_expected_values.sql")
    con.close()

    defined = MEASURE_PATTERN.findall((POWERBI_DIR / "measures.dax").read_text(encoding="utf-8"))
    validated = set(expected.measure)
    missing = [m for m in defined if m not in validated]
    unknown = sorted(validated - set(defined))
    if missing or unknown or expected.expected_value.isna().any():
        print(f"  measures without an expected value: {missing}")
        print(f"  expected values for unknown measures: {unknown}")
        print(f"  null expected values: {expected[expected.expected_value.isna()].measure.tolist()}")
        return 1

    expected["display"] = [format_value(v, u) for v, u in zip(expected.expected_value, expected.unit)]
    expected.to_csv(POWERBI_DIR / "expected_values.csv", index=False)

    lines = [
        "# Expected values for the Power BI measures",
        "",
        "Generated by `src/validate_dax.py` from `sql/validation/dax_expected_values.sql`.",
        "Each value is computed in SQL (DuckDB), independently of DAX. After building the report,",
        "put the measure in a Card (or a table with the stated filter) and compare.",
        "A mismatch means the measure, a relationship or a column type is wrong - fix it before",
        "trusting the dashboard.",
        "",
        f"{len(defined)} measures, {len(expected)} checks.",
        "",
        "| Measure | Filter context | Expected value |",
        "|---|---|---:|",
    ]
    lines += [f"| {r.measure} | {r.filter_context} | {r.display} |" for r in expected.itertuples()]
    (POWERBI_DIR / "EXPECTED_VALUES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  {len(defined)} measures validated with {len(expected)} expected values")
    return 0


if __name__ == "__main__":
    sys.exit(main())
